import { P, H2, UL, LI, Blockquote, Callout, Strong } from "./prose";

export default function WhatToWearHeadshotVancouver() {
  return (
    <>
      <P>
        Ninety percent of the emails I get before a headshot day are some
        version of the same question. What do I wear? People send me screenshots
        of their closet. They send me two options with a poll built in. They
        send me a photo of themselves in a shirt that is definitely too green
        and ask if it will work under studio light.
      </P>

      <P>
        The answer is almost always the same, so I am writing it down.
      </P>

      <H2>The three rules, before we get into anything specific</H2>

      <UL>
        <LI>
          <Strong>Solids beat patterns.</Strong> The camera does not care about
          your polka dots. It cares about your face. Patterns pull the eye off
          the face — and the face is what your LinkedIn viewer is trying to
          read. Solid, mid-saturation, matte fabric wins ninety percent of the
          time.
        </LI>
        <LI>
          <Strong>Texture beats sheen.</Strong> A merino sweater photographs
          better than a shiny synthetic. A raw silk blazer photographs better
          than a polyester blazer that catches every fluorescent overhead.
          Texture holds light in a way that flatters — sheen throws it back and
          gives the camera glare to fight.
        </LI>
        <LI>
          <Strong>One personal detail beats a costume.</Strong> If you always
          wear a specific necklace, wear it. If you never wear a tie, do not
          wear one for the shoot. Your headshot should look like you on your
          best Wednesday morning — not you at somebody&apos;s wedding.
        </LI>
      </UL>

      <Blockquote>
        If someone who knows you would look at this photo and say &ldquo;yeah
        that&rsquo;s them&rdquo; — you got it right. If they say &ldquo;oh wow
        you cleaned up&rdquo; — you overshot. That is a shoot-day rule.
      </Blockquote>

      <H2>What actually shows up well on the studio backdrop at Nook</H2>

      <P>
        My studio corner at Nook Coworking runs a soft dark backdrop and warm
        directional light. In that lighting, here is what tends to work:
      </P>

      <UL>
        <LI>
          <Strong>Deep jewel tones</Strong> — forest, teal, wine, mustard, deep
          navy. They separate cleanly from the backdrop without going too flat.
        </LI>
        <LI>
          <Strong>Warm neutrals</Strong> — camel, oatmeal, warm cream, terracotta.
          Especially good if your natural coloring runs warm.
        </LI>
        <LI>
          <Strong>Charcoal or dark grey</Strong> instead of straight black. Black
          on a dark backdrop turns your torso into a shadow.
        </LI>
        <LI>
          <Strong>Structured collars</Strong> — a crisp shirt, a well-fitted knit
          collar, a blazer with real shoulders. Structure at the neckline pulls
          the eye up to your face, which is the whole point.
        </LI>
      </UL>

      <H2>What does not work as often as people think</H2>

      <UL>
        <LI>
          <Strong>Pure white shirts</Strong> alone. They blow out under studio
          light and make your face look darker than it should. If you love a
          white shirt, layer a jacket or vest over it.
        </LI>
        <LI>
          <Strong>Anything with a logo</Strong>. It dates the photo instantly.
          You want this image to still be true in eighteen months.
        </LI>
        <LI>
          <Strong>Stripes narrower than a pencil</Strong>. They cause a shimmer
          effect on video and on stills at certain shutter speeds. Wider stripes
          are fine.
        </LI>
        <LI>
          <Strong>Brand-new clothing you have never worn</Strong>. It always
          looks like a costume. Break it in the week before, at least once.
        </LI>
      </UL>

      <H2>Grooming, glasses, and the small things</H2>

      <P>
        Hair on the day should be how you actually wear it, cleaned up a
        notch. If you always wear glasses, wear them — no camera-shy compromise.
        Your audience knows you in glasses. Anti-reflective coating is your
        friend on shoot day; I still light carefully around lenses but the
        coating gives me twice as much room to work.
      </P>

      <P>
        Facial hair: whatever you actually maintain, tidied. If you are between
        a beard and a shave, pick one. The camera reads &ldquo;between&rdquo; as
        &ldquo;messy.&rdquo; It is not fair. It is what the camera does.
      </P>

      <P>
        Makeup, if you wear it: matte finish, slightly more than daily. Studio
        light eats a little of what looks strong in the bathroom mirror.
        Powder for shine. If you never wear it, do not start on shoot day.
      </P>

      <Callout>
        <Strong>Pro tip that never gets old:</Strong> bring the top-of-shirt
        options on hangers rather than folded, and bring at least one backup
        blouse or shirt in a different color. Two shirts, one blazer, one
        accessory swap gives me four visibly different frames in the same
        session — that is your whole feed for a quarter, done in an hour.
      </Callout>

      <H2>Bring an old photo you like of yourself</H2>

      <P>
        Not to copy. To reference. If there is a picture of you from three years
        ago that you actually like — you know the one — bring it to the consult
        call. Nine times out of ten I can figure out what was working in that
        frame and give you a fresh version of it. Better light, better crop,
        current you. That is the whole game.
      </P>

      <P>
        The wardrobe is the container. The face is the photograph. If the
        wardrobe is doing more than fifteen percent of the work, we picked the
        wrong wardrobe.
      </P>
    </>
  );
}
